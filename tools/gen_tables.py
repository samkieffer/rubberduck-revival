#!/usr/bin/env python3
"""Generates the lookup tables of the engines from the original binaries:

    gen_tables.py rdh3o.exe core/src/Tables.cpp          (v2.12)
    gen_tables.py --v1 RUBDUCK.EXE core/src/TablesV1.cpp (v1.02)

The pitch table was computed by the original with x87 rounding that a modern
pow() does not reproduce bit for bit, and the pitch-drift lookup reads 256
bytes past its sine table, so both are copied verbatim.
"""
import struct
import sys

BASE = 0x400000


def load_image(path):
    data = open(path, 'rb').read()
    pe = struct.unpack_from('<I', data, 0x3c)[0]
    nsec = struct.unpack_from('<H', data, pe + 6)[0]
    opt = struct.unpack_from('<H', data, pe + 20)[0]
    sec = pe + 24 + opt
    image = {}
    for i in range(nsec):
        name, vsize, va, rsize, raw = struct.unpack_from('<8sIIII', data, sec + 40 * i)
        image[va] = (vsize, data[raw:raw + rsize])
    def read(addr, size):
        rva = addr - BASE
        for va, (vsize, blob) in image.items():
            if va <= rva < va + max(vsize, len(blob)):
                chunk = blob[rva - va:rva - va + size]
                return chunk + b'\0' * (size - len(chunk))
        raise ValueError(hex(addr))
    return read


def main(exe, out):
    read = load_image(exe)
    pitch = struct.unpack('<4096I', read(0x43df08, 4096 * 4))
    drift = struct.unpack('<512b', read(0x4351d8, 512))
    with open(out, 'w') as f:
        f.write('// Generated by tools/gen_tables.py from rdh3o.exe v2.12. Do not edit.\n')
        f.write('#include "rd/Tables.h"\n\nnamespace rd {\n\n')
        f.write('// 0.0625 * 2^(k/384), as float bit patterns (original 0x43df08).\n')
        f.write('const uint32_t kPitchTableBits[4096] = {\n')
        for i in range(0, 4096, 8):
            f.write('    ' + ', '.join('0x%08x' % v for v in pitch[i:i + 8]) + ',\n')
        f.write('};\n\n')
        f.write('// int(127 * sin(2 pi i / 256)) followed by the 256 bytes the original\n')
        f.write('// reads past the end of its table (original 0x4351d8).\n')
        f.write('const int8_t kDriftTable[512] = {\n')
        for i in range(0, 512, 16):
            f.write('    ' + ', '.join('%d' % v for v in drift[i:i + 16]) + ',\n')
        f.write('};\n\n} // namespace rd\n')


def main_v1(exe, out):
    read = load_image(exe)
    pitch = struct.unpack('<4096I', read(0x415030, 4096 * 4))
    drift = struct.unpack('<512b', read(0x412ce0, 512))
    with open(out, 'w') as f:
        f.write('// Generated by tools/gen_tables.py from RUBDUCK.EXE v1.02. Do not edit.\n')
        f.write('#include "rd/Tables.h"\n\nnamespace rd {\n\n')
        f.write('// 0.0625 * 2^(k/384) up to k = 3850, then whatever follows the table in\n')
        f.write('// .data, as float bit patterns (original 0x415030).\n')
        f.write('const uint32_t kPitchTableV1Bits[4096] = {\n')
        for i in range(0, 4096, 8):
            f.write('    ' + ', '.join('0x%08x' % v for v in pitch[i:i + 8]) + ',\n')
        f.write('};\n\n')
        f.write('// int(127 * sin(2 pi i / 256)) followed by the 256 bytes the original\n')
        f.write('// reads past the end of its table (original 0x412ce0).\n')
        f.write('const int8_t kDriftTableV1[512] = {\n')
        for i in range(0, 512, 16):
            f.write('    ' + ', '.join('%d' % v for v in drift[i:i + 16]) + ',\n')
        f.write('};\n\n} // namespace rd\n')


if __name__ == '__main__':
    if sys.argv[1] == '--v1':
        main_v1(sys.argv[2], sys.argv[3])
    else:
        main(sys.argv[1], sys.argv[2])
